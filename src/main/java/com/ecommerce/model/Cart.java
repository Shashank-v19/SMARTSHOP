package com.ecommerce.model;

public class Cart {

    private Long cartId;
    private Long userId;

    public Cart() {
    }

    public Cart(Long userId) {
        this.userId = userId;
    }

    public Long getCartId() {
        return cartId;
    }

    public void setCartId(Long cartId) {
        this.cartId = cartId;
    }

    public Long getUserId() {
        return userId;
    }

    public void setUserId(Long userId) {
        this.userId = userId;
    }
}